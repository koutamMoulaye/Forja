"""SQL rendering of a transformation plan into dbt models.

Each source yields three models:

- ``stg_<source>__checked`` (ephemeral): unprocessed Bronze rows, deduplicated,
  cleaned, cast and annotated with ``_reject_reason``;
- ``stg_<source>`` (incremental): rows without reject reason;
- ``stg_<source>__rejects`` (incremental): the others, with their raw values.
"""

from __future__ import annotations

from collections.abc import Iterable
from functools import cache

from forja_core import duck
from forja_core.profiling.types import ISO8601
from forja_core.silver.explain import DUPLICATE_KEY_REASON, reject_reason
from forja_core.silver.plan import (
    ColumnPlan,
    Normalization,
    RuleKind,
    SilverType,
    TransformationPlan,
)
from forja_core.silver.planner import needs_cast
from forja_core.utils import quote_ident, sql_literal

INDENT = "    "
RAW_SUFFIX = "__raw"
TECHNICAL_SELECT = ("_batch_id", "_ingested_at", "_source_file", "_row_hash")
TECHNICAL_TYPES: dict[str, str] = {
    "_batch_id": "varchar",
    "_ingested_at": "timestamp with time zone",
    "_source_file": "varchar",
    "_row_hash": "varchar",
    "_run_id": "varchar",
}

EMAIL_PATTERN = r"[^@\s]+@[^@\s]+\.[A-Za-z]{2,}"
PHONE_PATTERN = r"(\+|00)?[0-9]{8,15}"
PHONE_SEPARATORS = r"[\s.\-/()]"
IBAN_PATTERN = r"[A-Z]{2}[0-9]{2}[A-Z0-9]{11,30}"
FR_THOUSANDS = r"[ \x{00A0}\x{202F}.]"


def checked_model(plan: TransformationPlan) -> str:
    return f"{plan.model_name}__checked"


def rejects_model(plan: TransformationPlan) -> str:
    return f"{plan.model_name}__rejects"


@cache
def _keywords() -> frozenset[str]:
    with duck.connect() as con:
        rows = con.execute(
            "SELECT keyword_name FROM duckdb_keywords() WHERE keyword_category <> 'unreserved'"
        ).fetchall()
    return frozenset(str(row[0]).lower() for row in rows)


def ident(name: str) -> str:
    """Quote identifiers only when required, to keep the SQL readable."""
    if name.isidentifier() and name.islower() and name.isascii() and name not in _keywords():
        return name
    return quote_ident(name)


def raw_name(column: ColumnPlan) -> str:
    return f"{column.target_column}{RAW_SUFFIX}"


def _header(plan: TransformationPlan, purpose: str) -> str:
    return (
        f"-- {purpose}\n"
        f"-- Generated by Forja from transformation plan v{plan.version} "
        f"of source '{plan.source_name}'.\n"
        "-- Do not edit: this file is regenerated on each build.\n"
    )


def _select_list(expressions: Iterable[str], indent: int = 2) -> str:
    pad = INDENT * indent
    return (",\n").join(f"{pad}{e}" for e in expressions)


def _cte(name: str, body: str) -> str:
    indented = "\n".join(f"{INDENT}{line}" if line else "" for line in body.splitlines())
    return f"{name} as (\n\n{indented}\n\n)"


def null_markers_literal(values: Iterable[str]) -> str:
    return "(" + ", ".join(sql_literal(v) for v in ["", *values]) + ")"


def shared_null_markers(columns: Iterable[ColumnPlan]) -> tuple[str, ...] | None:
    """Null markers used by the columns, when they all use the same ones."""
    distinct = {tuple(c.cast.null_values) for c in columns if c.from_text and c.cast.null_values}
    return distinct.pop() if len(distinct) == 1 else None


def cleaned_expression(column: ColumnPlan, shared_markers: tuple[str, ...] | None = None) -> str:
    """Raw value as text, trimmed, with blank values and null markers turned into NULL."""
    source = ident(column.source_column)
    if not column.from_text:
        return source
    if column.cast.null_values:
        markers = (
            "{{ null_markers }}"
            if tuple(column.cast.null_values) == shared_markers
            else null_markers_literal(column.cast.null_values)
        )
        return f"case when lower(trim({source})) in {markers} then null else trim({source}) end"
    return f"nullif(trim({source}), '')"


def typed_expression(column: ColumnPlan) -> str:
    """Cast of the cleaned value to the target type; NULL when the value does not parse."""
    raw = raw_name(column)
    target = column.target_type
    if not column.from_text:
        function = "try_cast" if needs_cast(column) else "cast"
        return f"{function}({raw} as {target.value})"
    match target:
        case SilverType.VARCHAR:
            return _normalized(raw, column.normalization)
        case SilverType.BIGINT:
            return f"try_cast({raw} as bigint)"
        case SilverType.DOUBLE | SilverType.DECIMAL if column.cast.decimal_separator == ",":
            digits = f"regexp_replace({raw}, '{FR_THOUSANDS}', '', 'g')"
            return f"try_cast(replace({digits}, ',', '.') as {target.value})"
        case SilverType.DOUBLE | SilverType.DECIMAL:
            return f"try_cast(replace({raw}, ',', '') as {target.value})"
        case SilverType.BOOLEAN:
            trues = ", ".join(sql_literal(v) for v in column.cast.true_values)
            falses = ", ".join(sql_literal(v) for v in column.cast.false_values)
            return (
                f"case when lower({raw}) in ({trues}) then true "
                f"when lower({raw}) in ({falses}) then false end"
            )
        case SilverType.DATE:
            return f"cast(try_strptime({raw}, {sql_literal(_date_format(column))}) as date)"
        case SilverType.TIMESTAMP if column.cast.date_format in (None, ISO8601):
            return f"try_cast({raw} as timestamp)"
        case SilverType.TIMESTAMP:
            return f"try_strptime({raw}, {sql_literal(_date_format(column))})"


def _date_format(column: ColumnPlan) -> str:
    return column.cast.date_format or "%Y-%m-%d"


def _normalized(value: str, normalization: Normalization) -> str:
    match normalization:
        case Normalization.NONE | Normalization.TRIM:
            return value
        case Normalization.COLLAPSE_WHITESPACE:
            return f"regexp_replace({value}, '\\s+', ' ', 'g')"
        case Normalization.LOWERCASE:
            return f"lower(regexp_replace({value}, '\\s+', '', 'g'))"
        case Normalization.COMPACT_UPPERCASE:
            return f"upper(regexp_replace({value}, '\\s+', '', 'g'))"


def _rule_condition(column: ColumnPlan, kind: RuleKind) -> str:
    name = column.target_column
    value = ident(name)
    match kind:
        case RuleKind.CASTABLE:
            return f"{raw_name(column)} is not null and {value} is null"
        case RuleKind.NOT_NULL:
            return f"{value} is null"
        case RuleKind.EMAIL_FORMAT:
            return f"{value} is not null and not regexp_full_match({value}, '{EMAIL_PATTERN}')"
        case RuleKind.PHONE_FORMAT:
            compact = f"regexp_replace({value}, '{PHONE_SEPARATORS}', '', 'g')"
            return f"{value} is not null and not regexp_full_match({compact}, '{PHONE_PATTERN}')"
        case RuleKind.IBAN_FORMAT:
            compact = f"upper(replace({value}, ' ', ''))"
            return f"{value} is not null and not regexp_full_match({compact}, '{IBAN_PATTERN}')"


def _reject_checks(plan: TransformationPlan) -> list[tuple[str, str]]:
    """``(condition, reason)`` pairs, one per enabled validity rule."""
    checks: list[tuple[str, str]] = []
    for column in plan.included_columns():
        for rule in column.enabled_rules():
            checks.append((_rule_condition(column, rule.kind), reject_reason(column, rule.kind)))
    keys = [ident(c.target_column) for c in plan.key_columns()]
    if keys:
        not_null = " and ".join(f"{k} is not null" for k in keys)
        partition = ", ".join(["_batch_id", *keys])
        checks.append(
            (
                f"{not_null} and count(*) over (partition by {partition}) > 1",
                DUPLICATE_KEY_REASON,
            )
        )
    return checks


def _reject_reason_sql(checks: list[tuple[str, str]]) -> str:
    if not checks:
        return "cast(null as varchar) as _reject_reason"
    cases = ",\n".join(
        f"{INDENT * 2}case\n"
        f"{INDENT * 3}when {condition}\n"
        f"{INDENT * 4}then {sql_literal(reason)}\n"
        f"{INDENT * 2}end"
        for condition, reason in checks
    )
    return f"nullif(concat_ws('; ',\n{cases}\n{INDENT}), '') as _reject_reason"


def render_checked(plan: TransformationPlan) -> str:
    columns = plan.included_columns()
    ctes: list[str] = [
        _cte(
            "source",
            "select *\n"
            f"from {{{{ source('bronze', {sql_literal(plan.source_name)}) }}}}\n"
            f"{{{{ forja_unprocessed_rows({sql_literal(plan.model_name)}) }}}}",
        )
    ]
    upstream = "source"
    if plan.deduplication.enabled:
        ctes.append(
            _cte(
                "deduplicated",
                "-- Exact duplicates share the same _row_hash: keep the first occurrence.\n"
                "select *\n"
                "from source\n"
                "qualify row_number() over (\n"
                f"{INDENT}partition by _row_hash order by _ingested_at, _batch_id\n"
                ") = 1",
            )
        )
        upstream = "deduplicated"

    markers = shared_null_markers(columns)
    cleaned = [f"{cleaned_expression(c, markers)} as {ident(raw_name(c))}" for c in columns]
    ctes.append(
        _cte(
            "cleaned",
            "-- Text trimmed, blank values and null markers turned into NULL.\n"
            "select\n"
            f"{_select_list([*cleaned, *TECHNICAL_SELECT], indent=1)}\n"
            f"from {upstream}",
        )
    )

    typed = [f"{typed_expression(c)} as {ident(c.target_column)}" for c in columns]
    ctes.append(
        _cte(
            "typed",
            "-- Values that do not parse become NULL here and are caught by the checks below.\n"
            "select\n"
            f"{_select_list([*typed, 'cleaned.*'], indent=1)}\n"
            "from cleaned",
        )
    )

    ctes.append(
        _cte(
            "checked",
            "-- Every failed rule is listed; a row with a reason goes to the rejects table.\n"
            f"select\n{INDENT}*,\n{INDENT}{_reject_reason_sql(_reject_checks(plan))}\n"
            "from typed",
        )
    )

    preamble = ""
    if markers is not None:
        preamble = f'{{%- set null_markers = "{null_markers_literal(markers)}" -%}}\n'
    return (
        _header(plan, "Bronze rows not processed yet, cleaned, cast and checked.")
        + "\n{{ config(materialized='ephemeral') }}\n"
        + preamble
        + "\nwith "
        + ",\n\n".join(ctes)
        + "\n\nselect * from checked\n"
    )


def _incremental_config(unique_key: str | None) -> str:
    lines = [
        "materialized='incremental'",
        *(
            [f"unique_key={unique_key}", "incremental_strategy='delete+insert'"]
            if unique_key
            else []
        ),
        "on_schema_change='append_new_columns'",
    ]
    body = ",\n".join(f"{INDENT * 2}{line}" for line in lines)
    return f"{{{{\n{INDENT}config(\n{body}\n{INDENT})\n}}}}"


def render_silver(plan: TransformationPlan) -> str:
    keys = [c.target_column for c in plan.key_columns()]
    unique_key = (
        (sql_literal(keys[0]) if len(keys) == 1 else f"[{', '.join(sql_literal(k) for k in keys)}]")
        if keys
        else sql_literal("_row_hash")
    )
    columns = [ident(c.target_column) for c in plan.included_columns()]
    run_id = '\'{{ var("forja_run_id", "manual") }}\' as _run_id'

    body = [
        _cte(
            "valid",
            f"select *\nfrom {{{{ ref({sql_literal(checked_model(plan))}) }}}}\n"
            "where _reject_reason is null",
        )
    ]
    upstream = "valid"
    if keys:
        partition = ", ".join(ident(k) for k in keys)
        body.append(
            _cte(
                "latest",
                "-- Several unprocessed batches may carry the same key: the most recent wins.\n"
                "select *\n"
                "from valid\n"
                "qualify row_number() over (\n"
                f"{INDENT}partition by {partition} order by _ingested_at desc, _row_hash\n"
                ") = 1",
            )
        )
        upstream = "latest"

    return (
        _header(plan, f"Silver table of source '{plan.source_name}': valid rows only.")
        + "\n"
        + _incremental_config(unique_key)
        + "\n\nwith "
        + ",\n\n".join(body)
        + "\n\nselect\n"
        + _select_list([*columns, *TECHNICAL_SELECT, run_id], indent=1)
        + f"\nfrom {upstream}\n"
    )


def render_rejects(plan: TransformationPlan) -> str:
    raw_columns = [
        f"cast({ident(raw_name(c))} as varchar) as {ident(c.target_column)}"
        for c in plan.included_columns()
    ]
    run_id = '\'{{ var("forja_run_id", "manual") }}\' as _run_id'
    return (
        _header(
            plan,
            f"Quarantine of source '{plan.source_name}': rows failing a validity rule, "
            "kept with their raw values.",
        )
        + "\n"
        + _incremental_config(None)
        + "\n\nselect\n"
        + _select_list([*raw_columns, "_reject_reason", *TECHNICAL_SELECT, run_id], indent=1)
        + f"\nfrom {{{{ ref({sql_literal(checked_model(plan))}) }}}}\n"
        + "where _reject_reason is not null\n"
    )


UNPROCESSED_ROWS_MACRO = """\
{#-
    Restricts a Bronze read to rows whose _row_hash is in neither the Silver table
    nor its rejects, so that each row is processed once. Disabled on full refresh.
    Generated by Forja. Do not edit: the file is regenerated on each build.
-#}
{% macro forja_unprocessed_rows(model_name) %}
    {%- if execute and not flags.FULL_REFRESH -%}
        {%- set processed = [] -%}
        {%- for identifier in [model_name, model_name ~ '__rejects'] -%}
            {%- set relation = adapter.get_relation(
                database=target.database, schema=target.schema, identifier=identifier
            ) -%}
            {%- if relation is not none -%}
                {%- do processed.append('select _row_hash from ' ~ relation) -%}
            {%- endif -%}
        {%- endfor -%}
        {%- if processed %}
where _row_hash not in (
    {{ processed | join('\\n    union all\\n    ') }}
)
        {%- endif -%}
    {%- endif -%}
{% endmacro %}
"""

UNIQUE_COMBINATION_TEST = """\
{#-
    Fails when a combination of columns is not unique (composite primary keys).
    Generated by Forja. Do not edit: the file is regenerated on each build.
-#}
{% test forja_unique_combination(model, columns) %}

select
    {{ columns | join(',\\n    ') }},
    count(*) as occurrences
from {{ model }}
group by {{ columns | join(', ') }}
having count(*) > 1

{% endtest %}
"""
