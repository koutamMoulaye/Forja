"""Compilation of an approved Gold plan into dbt models, snapshots and tests.

- ``dim_<name>``: one row per natural key (SCD1) or per version (SCD2, from a dbt
  snapshot of the Silver table), a surrogate key that is an MD5 of the natural key
  (and of the version start for SCD2), and an "unknown" member keyed ``-1``.
- ``dim_date``: one row per day between the earliest and latest fact date, keyed
  YYYYMMDD, plus the unknown member ``-1``.
- ``fct_<name>``: the fact source at its grain, left-joined to its header tables and
  dimensions. A foreign key without a match takes the unknown member instead of
  dropping the fact row; SCD2 dimensions are matched on the version valid at the
  fact date.
"""

from __future__ import annotations

from typing import Any

from forja_core.gold.context import GoldContext
from forja_core.gold.expressions import check_expression
from forja_core.gold.plan import (
    DATE_DIMENSION,
    UNKNOWN_KEY,
    Dimension,
    Fact,
    GoldPlan,
    ScdType,
)
from forja_core.silver.dbt.sql import ident
from forja_core.utils import sql_literal

INDENT = "    "
UNKNOWN_LABEL = "Inconnu"
VALID_FROM_ORIGIN = "TIMESTAMP '1900-01-01 00:00:00'"
VALID_TO_END = "TIMESTAMP '9999-12-31 00:00:00'"
_MONTHS = (
    "janvier", "février", "mars", "avril", "mai", "juin", "juillet", "août", "septembre",
    "octobre", "novembre", "décembre",
)  # fmt: skip
_DAYS = ("lundi", "mardi", "mercredi", "jeudi", "vendredi", "samedi", "dimanche")


def _q(name: str) -> str:
    return ident(name)


def _select_list(items: list[str]) -> str:
    """Select items, one per line; items starting with ``--`` are section comments."""
    expressions = [i for i in items if not i.startswith("--")]
    last = expressions[-1] if expressions else None
    lines = []
    for item in items:
        suffix = "" if item.startswith("--") or item is last else ","
        lines.append(f"{INDENT}{item}{suffix}")
    return "\n".join(lines)


def _header(plan: GoldPlan, purpose: str) -> str:
    return (
        f"-- {purpose}\n"
        f"-- Generated by Forja from Gold plan v{plan.version}.\n"
        "-- Do not edit: this file is regenerated on each build.\n"
    )


def _list(items: list[str], indent: int = 2) -> str:
    pad = INDENT * indent
    return ",\n".join(f"{pad}{item}" for item in items)


def _column(table: str, column: str, name: str) -> str:
    reference = f"{_q(table)}.{_q(column)}"
    return reference if name == column else f"{reference} as {_q(name)}"


def _ref_cte(name: str, model: str) -> str:
    return f"{_q(name)} as (\n\n{INDENT}select * from {{{{ ref({sql_literal(model)}) }}}}\n\n)"


def snapshot_name(dim: Dimension) -> str:
    return f"snap_{dim.source}"


def silver_model(source: str) -> str:
    return f"stg_{source}"


def _hash_key(columns: list[str], extra: str | None = None, table: str | None = None) -> str:
    prefix = f"{_q(table)}." if table else ""
    parts = [f"cast({prefix}{_q(c)} as varchar)" for c in columns]
    if extra:
        parts.append(f"cast({extra} as varchar)")
    if len(parts) == 1:
        return f"md5({parts[0]})"
    return f"md5(concat_ws('|', {', '.join(parts)}))"


def _unknown_value(column_type: str) -> str:
    if column_type.upper() == "VARCHAR":
        return sql_literal(UNKNOWN_LABEL)
    return f"cast(null as {column_type.lower()})"


def render_dimension(plan: GoldPlan, dim: Dimension, ctx: GoldContext) -> str:
    source = ctx.sources[dim.source]
    columns = [*dim.natural_key, *(a.column for a in dim.attributes)]
    names = {a.column: a.name for a in dim.attributes}
    selected = [
        f"{_q(c)} as {_q(names.get(c, c))}" if names.get(c, c) != c else _q(c) for c in columns
    ]
    unknown = [f"cast(null as {source.columns[c].lower()}) as {_q(c)}" for c in dim.natural_key] + [
        f"{_unknown_value(source.columns[a.column])} as {_q(a.name)}" for a in dim.attributes
    ]
    historized = dim.scd is ScdType.SCD2
    upstream = snapshot_name(dim) if historized else silver_model(dim.source)

    ctes = [f"source as (\n\n{INDENT}select * from {{{{ ref({sql_literal(upstream)}) }}}}\n\n)"]
    if historized:
        partition = ", ".join(_q(c) for c in dim.natural_key)
        ctes.append(
            "versions as (\n\n"
            f"{INDENT}select\n{INDENT * 2}*,\n"
            f"{INDENT * 2}row_number() over (partition by {partition} order by dbt_valid_from)"
            " as version_number\n"
            f"{INDENT}from source\n\n)"
        )
        key = _hash_key(dim.natural_key, extra="dbt_valid_from")
        members = [
            f"{key} as {_q(dim.surrogate_key)}",
            *selected,
            "-- The first version is valid since the origin: older facts find it too.\n"
            f"{INDENT * 2}case when version_number = 1 then {VALID_FROM_ORIGIN} "
            "else cast(dbt_valid_from as timestamp) end as valid_from",
            f"coalesce(cast(dbt_valid_to as timestamp), {VALID_TO_END}) as valid_to",
            "dbt_valid_to is null as is_current",
        ]
        unknown += [
            f"{VALID_FROM_ORIGIN} as valid_from",
            f"{VALID_TO_END} as valid_to",
            "true as is_current",
        ]
        member_source = "versions"
    else:
        members = [f"{_hash_key(dim.natural_key)} as {_q(dim.surrogate_key)}", *selected]
        member_source = "source"

    ctes.append(
        f"members as (\n\n{INDENT}select\n{_list(members)}\n{INDENT}from {member_source}\n\n)"
    )
    ctes.append(
        "unknown_member as (\n\n"
        f"{INDENT}-- Target of the foreign keys that match no member.\n"
        f"{INDENT}select\n"
        + _list([f"{sql_literal(UNKNOWN_KEY)} as {_q(dim.surrogate_key)}", *unknown])
        + "\n\n)"
    )
    return (
        _header(plan, f"Dimension {dim.name} ({dim.scd.value}) built from {dim.source}.")
        + "\n{{ config(materialized='table') }}\n\nwith "
        + ",\n\n".join(ctes)
        + "\n\nselect * from members\nunion all\nselect * from unknown_member\n"
    )


def render_snapshot(dim: Dimension) -> dict[str, Any]:
    return {
        "name": snapshot_name(dim),
        "relation": f"ref('{silver_model(dim.source)}')",
        "description": f"Historique des versions de {dim.source} pour {dim.name} (SCD2).",
        "config": {
            "unique_key": dim.natural_key[0] if len(dim.natural_key) == 1 else dim.natural_key,
            "strategy": "check",
            "check_cols": [a.column for a in dim.attributes] or list(dim.natural_key),
        },
    }


def _date_columns(plan: GoldPlan) -> list[tuple[str, str]]:
    return sorted({(k.source, k.column) for f in plan.facts for k in f.date_keys})


def render_date_dimension(plan: GoldPlan) -> str:
    sources = _date_columns(plan)
    union = f"\n{INDENT * 2}union all\n".join(
        f"{INDENT * 2}select cast({_q(column)} as date) as day "
        f"from {{{{ ref({sql_literal(silver_model(source))}) }}}}"
        for source, column in sources
    )
    months = " ".join(f"when {i} then {sql_literal(m)}" for i, m in enumerate(_MONTHS, 1))
    days = " ".join(f"when {i} then {sql_literal(d)}" for i, d in enumerate(_DAYS, 1))
    return (
        _header(plan, "Calendar dimension covering every date used by the facts.")
        + "\n{{ config(materialized='table') }}\n\n"
        "with fact_dates as (\n\n"
        f"{INDENT}select day from (\n{union}\n{INDENT}) where day is not null\n\n),\n\n"
        "bounds as (\n\n"
        f"{INDENT}select min(day) as first_day, max(day) as last_day from fact_dates\n\n),\n\n"
        "days as (\n\n"
        f"{INDENT}select cast(unnest(range(first_day, last_day + interval 1 day, interval 1 day))"
        " as date) as day\n"
        f"{INDENT}from bounds\n{INDENT}where first_day is not null\n\n)\n\n"
        "select\n"
        + _list(
            [
                "cast(strftime(day, '%Y%m%d') as integer) as date_key",
                "day as date",
                "year(day) as annee",
                "quarter(day) as trimestre",
                "month(day) as mois",
                f"case month(day) {months} end as nom_mois",
                "weekofyear(day) as semaine_iso",
                "day(day) as jour",
                "isodow(day) as jour_semaine",
                f"case isodow(day) {days} end as nom_jour",
                "isodow(day) >= 6 as est_week_end",
            ],
            indent=1,
        )
        + "\nfrom days\nunion all\nselect\n"
        + _list(
            [
                "-1 as date_key",
                "cast(null as date) as date",
                *(f"cast(null as integer) as {c}" for c in ("annee", "trimestre", "mois")),
                f"{sql_literal(UNKNOWN_LABEL)} as nom_mois",
                *(f"cast(null as integer) as {c}" for c in ("semaine_iso", "jour", "jour_semaine")),
                f"{sql_literal(UNKNOWN_LABEL)} as nom_jour",
                "cast(null as boolean) as est_week_end",
            ],
            indent=1,
        )
        + "\n"
    )


def _fact_event(fact: Fact, ctx: GoldContext) -> str | None:
    """The fact date used to pick the SCD2 version valid at the time of the fact."""
    for key in fact.date_keys:
        return f"{_q(key.source)}.{_q(key.column)}"
    return None


def render_fact(plan: GoldPlan, fact: Fact, ctx: GoldContext) -> str:
    dimensions = {d.name: d for d in plan.dimensions}
    tables = {fact.source: set(ctx.sources[fact.source].columns)}
    for join in fact.joins:
        tables[join.source] = set(ctx.sources[join.source].columns)

    ctes = [_ref_cte(name, silver_model(name)) for name in tables]
    used_dims = list(dict.fromkeys(fk.dimension for fk in fact.foreign_keys))
    ctes += [_ref_cte(name, name) for name in used_dims]

    degenerate = {(d.source, d.column): d.name for d in fact.degenerate_dimensions}
    columns: list[str] = ["-- Grain and degenerate dimensions"]
    emitted: set[str] = set()
    for column in fact.grain:
        name = degenerate.get((fact.source, column), column)
        columns.append(_column(fact.source, column, name))
        emitted.add(name)
    for (source, column), name in degenerate.items():
        if name not in emitted:
            columns.append(_column(source, column, name))
            emitted.add(name)

    columns.append("-- Foreign keys: the unknown member when the dimension has no match")
    joins: list[str] = [f"from {_q(fact.source)}"]
    for join in fact.joins:
        joins.append(
            f"left join {_q(join.source)}\n{INDENT}on {_q(join.source)}.{_q(join.to_column)} = "
            f"{_q(join.from_source)}.{_q(join.from_column)}"
        )
    event = _fact_event(fact, ctx)
    for fk in fact.foreign_keys:
        dim = dimensions[fk.dimension]
        alias = (
            fk.name
            if len([f for f in fact.foreign_keys if f.dimension == dim.name]) > 1
            else dim.name
        )
        surrogate = f"{_q(alias)}.{_q(dim.surrogate_key)}"
        columns.append(f"coalesce({surrogate}, {sql_literal(UNKNOWN_KEY)}) as {_q(fk.name)}")
        condition = f"{_q(alias)}.{_q(dim.natural_key[0])} = {_q(fk.source)}.{_q(fk.column)}"
        if dim.scd is ScdType.SCD2:
            if event is None:
                condition += f"\n{INDENT}and {_q(alias)}.is_current"
            else:
                condition += (
                    f"\n{INDENT}and (\n"
                    f"{INDENT * 2}({event} is null and {_q(alias)}.is_current)\n"
                    f"{INDENT * 2}or (\n"
                    f"{INDENT * 3}{event} >= {_q(alias)}.valid_from\n"
                    f"{INDENT * 3}and {event} < {_q(alias)}.valid_to\n"
                    f"{INDENT * 2})\n{INDENT})"
                )
        source_alias = _q(dim.name) if alias == dim.name else f"{_q(dim.name)} as {_q(alias)}"
        joins.append(f"left join {source_alias}\n{INDENT}on {condition}")
    for key in fact.date_keys:
        columns.append(
            f"coalesce(cast(strftime({_q(key.source)}.{_q(key.column)}, '%Y%m%d') as integer), -1)"
            f" as {_q(key.name)}"
        )

    columns.append("-- Measures (row level; default aggregation in schema.yml)")
    for measure in fact.measures:
        checked = check_expression(measure.expression, tables, fact.source)
        expression = checked.sql
        bare = f"{_q(fact.source)}.{_q(measure.name)}"
        columns.append(expression if expression == bare else f"{expression} as {_q(measure.name)}")

    select = _select_list(columns)
    return (
        _header(plan, f"Fact {fact.name} at the grain of {fact.source}.")
        + "\n{{ config(materialized='table') }}\n\nwith "
        + ",\n\n".join(ctes)
        + "\n\nselect\n"
        + select
        + "\n"
        + "\n".join(joins)
        + "\n"
    )


def _dimension_schema(dim: Dimension, ctx: GoldContext) -> dict[str, Any]:
    key_tests: list[Any] = ["unique", "not_null"]
    columns: list[dict[str, Any]] = [
        {
            "name": dim.surrogate_key,
            "description": "Clé de substitution (MD5 de la clé naturelle"
            + (" et du début de version" if dim.scd is ScdType.SCD2 else "")
            + f") ; {UNKNOWN_KEY} pour le membre inconnu.",
            "data_tests": key_tests,
        }
    ]
    for column in dim.natural_key:
        columns.append({"name": column, "description": f"Clé naturelle issue de {dim.source}."})
    for attribute in dim.attributes:
        columns.append(
            {
                "name": attribute.name,
                "description": attribute.description
                or f"Attribut issu de {dim.source}.{attribute.column}.",
            }
        )
    if dim.scd is ScdType.SCD2:
        columns += [
            {"name": "valid_from", "description": "Début de validité de la version."},
            {"name": "valid_to", "description": "Fin de validité (9999-12-31 si en cours)."},
            {"name": "is_current", "description": "Vrai pour la version en cours."},
        ]
    return {"name": dim.name, "description": dim.explanation, "columns": columns}


def _fact_schema(plan: GoldPlan, fact: Fact) -> dict[str, Any]:
    dimensions = {d.name: d for d in plan.dimensions}
    degenerate = {(d.source, d.column): d.name for d in fact.degenerate_dimensions}
    grain = [degenerate.get((fact.source, c), c) for c in fact.grain]
    columns: list[dict[str, Any]] = []
    for fk in fact.foreign_keys:
        dim = dimensions[fk.dimension]
        columns.append(
            {
                "name": fk.name,
                "description": fk.explanation,
                "data_tests": [
                    "not_null",
                    {
                        "relationships": {
                            "arguments": {"to": f"ref('{dim.name}')", "field": dim.surrogate_key}
                        }
                    },
                ],
            }
        )
    for key in fact.date_keys:
        columns.append(
            {
                "name": key.name,
                "description": key.explanation,
                "data_tests": [
                    "not_null",
                    {
                        "relationships": {
                            "arguments": {"to": f"ref('{DATE_DIMENSION}')", "field": "date_key"}
                        }
                    },
                ],
            }
        )
    for measure in fact.measures:
        columns.append(
            {
                "name": measure.name,
                "description": measure.explanation,
                "meta": {"aggregation": measure.aggregation.value},
            }
        )
    return {
        "name": fact.name,
        "description": f"{fact.explanation} Grain : {', '.join(grain)}.",
        "data_tests": [{"forja_unique_combination": {"arguments": {"columns": grain}}}],
        "columns": columns,
    }


def render_gold(plan: GoldPlan, ctx: GoldContext) -> tuple[dict[str, str], dict[str, Any]]:
    """SQL files by path, and the Gold part of the YAML (models and snapshots)."""
    files: dict[str, str] = {}
    models: list[dict[str, Any]] = []
    snapshots: list[dict[str, Any]] = []
    for dim in sorted(plan.dimensions, key=lambda d: d.name):
        files[f"models/gold/{dim.name}.sql"] = render_dimension(plan, dim, ctx)
        models.append(_dimension_schema(dim, ctx))
        if dim.scd is ScdType.SCD2:
            snapshots.append(render_snapshot(dim))
    if plan.date_dimension.enabled and _date_columns(plan):
        files[f"models/gold/{DATE_DIMENSION}.sql"] = render_date_dimension(plan)
        models.append(
            {
                "name": DATE_DIMENSION,
                "description": plan.date_dimension.explanation,
                "columns": [{"name": "date_key", "data_tests": ["unique", "not_null"]}],
            }
        )
    for fact in sorted(plan.facts, key=lambda f: f.name):
        files[f"models/gold/{fact.name}.sql"] = render_fact(plan, fact, ctx)
        models.append(_fact_schema(plan, fact))
    return files, {"models": models, "snapshots": snapshots}


def gold_nodes(plan: GoldPlan) -> list[str]:
    """dbt node names built by build_gold, in dependency order."""
    nodes = [snapshot_name(d) for d in plan.dimensions if d.scd is ScdType.SCD2]
    nodes += [d.name for d in plan.dimensions]
    if plan.date_dimension.enabled and _date_columns(plan):
        nodes.append(DATE_DIMENSION)
    nodes += [f.name for f in plan.facts]
    return nodes
